"""Replay preserved, separately built Java evidence through the new storage ports.

No target application source is copied or launched. Provide inputs generated by
the method_evidence index CLI and an allowlisted logging-OTLP telemetry file.
"""
import argparse
from dataclasses import asdict
import json
import os
from pathlib import Path
import uuid

from tools.method_evidence.evidence import MAX_BYTES, file_digest, method_key, read_otlp
from .contracts import EvidenceReader, GraphRequest, SnapshotRef
from .postgres import PostgresEvidenceStore


def expected_reachable(index, analyzer, root, depth):
    """Independent unbounded-per-layer oracle for these small preserved fixtures."""
    tool = index["staticEvidence"][analyzer]
    inventory = {method_key(item) for item in tool["methods"]}
    seen, frontier = {root}, {root}
    for _ in range(depth):
        targets = {method_key(call["target"]) for call in tool["calls"]
                   if method_key(call["caller"]) in frontier and method_key(call["target"]) in inventory}
        frontier = targets - seen
        seen.update(frontier)
    return seen


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("index-a", "index-b", "log", "output"):
        parser.add_argument("--" + name, type=Path, required=True)
    parser.add_argument("--telemetry-config", required=True)
    parser.add_argument("--tenant", default="replay-" + uuid.uuid4().hex)
    args = parser.parse_args()
    indices = []
    for path in (args.index_a, args.index_b):
        with path.open("rb") as stream:
            raw = stream.read(MAX_BYTES + 1)
        if len(raw) > MAX_BYTES:
            raise ValueError("Index exceeds local budget")
        indices.append(json.loads(raw))
    if indices[0]["buildIdentity"] == indices[1]["buildIdentity"]:
        raise ValueError("Need two distinct builds")
    store = PostgresEvidenceStore(os.environ["JJAMTONG_EVIDENCE_DSN"])
    store.initialize()
    graphs, publications = [], []
    for index in indices:
        ref = SnapshotRef(args.tenant, index["analysisRunId"], index["indexSha256"])
        publications.append({"runId": ref.run_id, "created": store.publish(args.tenant, index)})
        if type(store)(store.dsn).load(ref) != index:
            raise AssertionError("Persisted document differs")
        reader = EvidenceReader(store, store)
        for analyzer in ("javaparser", "wala"):
            roots = [method_key(item) for item in index["staticEvidence"][analyzer]["methods"]
                     if item["class"] == "fixture.board.Service" and item["name"] == "list"]
            if len(roots) != 1:
                raise ValueError("Expected the preserved method-observability Service.list fixture")
            result = reader.graph(GraphRequest(ref, analyzer, roots[0], max_depth=4))
            actual = {tuple(item) for item in result.methods}
            if actual != expected_reachable(index, analyzer, roots[0], 4):
                raise AssertionError("Graph differs from independent source-edge traversal")
            graphs.append({"runId": ref.run_id, "analyzer": analyzer, "result": asdict(result)})
    collection = read_otlp(args.log)
    if not collection["spans"]:
        raise ValueError("Need collected method spans")
    trace_id = collection["spans"][0]["traceId"]
    results = []
    for index in indices:
        ref = SnapshotRef(args.tenant, index["analysisRunId"], index["indexSha256"])
        results.append(EvidenceReader(store, store).trace(ref, collection, trace_id, args.telemetry_config))
    if [item["status"] for item in results] != ["OBSERVED", "MISMATCH"]:
        raise AssertionError("Old trace must match only its actual build")
    report = {"schema": "jjamtong.evidence-store-replay.v1", "tenant": args.tenant,
              "inputs": [{"name": p.name, "sha256": file_digest(p)}
                         for p in (args.index_a, args.index_b, args.log)],
              "sources": {p.name: file_digest(p) for p in sorted(Path(__file__).parent.iterdir())
                          if p.suffix in (".py", ".sql", ".yaml")},
              "serverVersion": None, "publications": publications,
              "graphChecks": graphs, "traceStatuses": [item["status"] for item in results],
              "traceSpanCounts": [len(item["spans"]) for item in results],
              "limitations": ["Replays preserved local synthetic Java analysis and telemetry; no fresh JVM run.",
                              "Tenant labels are SQL scopes, not authentication or row-level authorization.",
                              "Small fixture correctness only; no throughput, HA or capacity claim."]}
    with store._connect() as conn:
        report["serverVersion"] = conn.execute("SHOW server_version").fetchone()[0]
    args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({"output": str(args.output), "graphChecks": len(graphs),
                      "traceStatuses": report["traceStatuses"]}))


if __name__ == "__main__":
    main()
